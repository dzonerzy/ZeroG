#!/usr/bin/env python3
"""Render the design verification workflow's journal into a Markdown report.

The verification ran one agent per area over ZeroG.md's claims against the
pinned WebKit checkout, then an independent skeptic re-checked every claim
judged REFUTED or PARTIAL. The final verdict is the skeptic's when there is one.

    verification_report.py extract <journal.jsonl> <transcripts dir> <data.json>
    verification_report.py render <data.json> <out.md> [--summary <summary.md>]
"""

import argparse
import json
import re
from collections import Counter
from pathlib import Path

ORDER = ["cmake-port", "wtf-runloop-threads", "webcore-embedding", "graphics-skia", "network-storage",
         "feature-flags-deps", "jsc-jit-bindings", "external-refs", "doc-consistency"]


def cell(text, limit=None):
    text = " ".join(str(text or "").split()).replace("|", "\\|")
    return text if not limit or len(text) <= limit else text[:limit - 1] + "…"


def claim_of_prompt(transcript):
    """The claim text a challenge agent was asked to re-check (from its transcript)."""
    for line in transcript.read_text(encoding="utf-8").splitlines():
        match = re.search(r"Claim: (.*?)\\n\s*Doc section:", line)
        if match:
            return json.loads(f'"{match.group(1)}"')
    return None


def load_journal(journal, transcripts):
    """Area results with each skeptic re-check merged into its claim. The journal
    keeps every agent's result separately; the claim a re-check belongs to is only
    in the agent's prompt, so transcripts are needed."""
    rows = [json.loads(line) for line in Path(journal).read_text(encoding="utf-8").splitlines() if line.strip()]
    started = [r for r in rows if r.get("type") == "started"]
    labels = {r["key"]: r.get("label", "") for r in started}
    agents = {}
    for r in started:
        agents.setdefault(r["key"], []).append(r["agentId"])
    results = {r["key"]: r.get("result") or r.get("value") for r in rows if r.get("type") == "result"}
    areas = {labels[k].split(":", 1)[1]: v for k, v in results.items()
             if labels.get(k, "").startswith("verify:") and isinstance(v, dict)}
    for key, verdict in results.items():
        if not labels.get(key, "").startswith("challenge:") or not isinstance(verdict, dict):
            continue
        area = areas.get(labels[key].split(":", 1)[1])
        claim_text = next((c for c in (claim_of_prompt(Path(transcripts) / f"agent-{a}.jsonl")
                                       for a in agents[key] if (Path(transcripts) / f"agent-{a}.jsonl").exists())
                           if c), None)
        claim = next((c for c in area["claims"] if c["claim"] == claim_text), None) if area else None
        if claim is None:
            raise SystemExit(f"challenge {key} could not be matched to a claim")
        claim["challenge"] = verdict
    return areas


def load(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def final(claim):
    challenge = claim.get("challenge")
    if challenge:
        return challenge["corrected_verdict"], challenge
    return claim["verdict"], None


def render(areas, summary):
    out = ["# Verification of ZeroG.md against WebKit 31a83a39", "",
           "Generated by `tools/verification_report.py` from the verification workflow: one agent per area "
           "checked every claim of [ZeroG.md](../../ZeroG.md) against the WebKit checkout pinned in "
           "`WEBKIT_REVISION` (main, 2026-10-28); an independent skeptic re-checked every claim judged "
           "REFUTED or PARTIAL and tried to overturn it. **Final** is the skeptic's verdict when one exists.", ""]
    totals = Counter()
    flips = 0
    for area in areas.values():
        for c in area["claims"]:
            v, ch = final(c)
            totals[v] += 1
            flips += bool(ch and not ch["original_verdict_holds"])
    out += [f"Claims: {sum(totals.values())} — " + ", ".join(f"{k} {v}" for k, v in totals.most_common())
            + f". Verdicts changed by the skeptic: {flips}.", ""]
    if summary:
        out += [summary.strip(), ""]
    for key in ORDER:
        if key not in areas:
            continue
        area = areas[key]
        out += [f"## {area['area']}", "", "| Claim | Final | Evidence | Implication |", "| --- | --- | --- | --- |"]
        for c in area["claims"]:
            v, ch = final(c)
            verdict = v if not ch or ch["original_verdict_holds"] else f"{v} (was {c['verdict']})"
            evidence = c["evidence"] if not ch else f"{c['evidence']} — skeptic: {ch['evidence']}"
            out.append(f"| {cell(c['claim'])} | {verdict} | {cell(evidence, 900)} | {cell(c['implication'], 700)} |")
        out += ["", "**Facts the doc misses**", ""]
        out += [f"- {cell(m)}" for m in area["missing_facts"]]
        if area.get("concrete_artifacts", "").strip():
            out += ["", "<details><summary>Concrete starting material</summary>", "", "```text",
                    area["concrete_artifacts"].strip(), "```", "", "</details>"]
        out.append("")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    extract = sub.add_parser("extract")
    extract.add_argument("journal")
    extract.add_argument("transcripts")
    extract.add_argument("data")
    rend = sub.add_parser("render")
    rend.add_argument("data")
    rend.add_argument("out")
    rend.add_argument("--summary")
    args = parser.parse_args()
    if args.command == "extract":
        areas = load_journal(args.journal, args.transcripts)
        Path(args.data).write_text(json.dumps(areas, indent=1, ensure_ascii=False), encoding="utf-8")
        merged = sum("challenge" in c for a in areas.values() for c in a["claims"])
        print(f"wrote {args.data}: {len(areas)} areas, {merged} challenges merged")
        return
    summary = Path(args.summary).read_text(encoding="utf-8") if args.summary else ""
    Path(args.out).write_text(render(load(args.data), summary), encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
