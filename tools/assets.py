#!/usr/bin/env python3
"""Pack a directory into a ZeroG asset archive for zg_context_mount_assets
(ZeroG.md, "Schema custom app://"): the application's frontend, embedded in its
binary and served from memory under app://.

Each file is stored as is or zlib-compressed, whichever is smaller; formats that
are already compressed (images, fonts, media, archives) are stored. The engine
inflates a compressed entry on its first request and keeps the result.

Format (little-endian), read by port/embedding/MemoryFS.cpp:
    header, 16 bytes:  "ZGAR", u32 version (1), u32 file count, u32 flags (0)
    entries, 40 bytes each:
        u64 data offset, u64 stored size, u64 size,
        u32 path offset, u32 path length, u32 MIME offset, u16 MIME length,
        u8 compression (0 stored, 1 zlib), u8 reserved
    then the strings (UTF-8 paths and MIME types) and the data.
Offsets are from the start of the archive; paths are "/"-rooted ("/js/app.js").
An empty MIME type means the engine derives it from the extension.

Usage:
    assets.py <directory> -o app.zga
    assets.py <directory> -o app.c --c-symbol app_assets     # C source to compile in
    assets.py <directory> -o app.zga --mime .wasm=application/wasm --exclude '*.map'

The C source defines `const unsigned char <symbol>[]` and
`const size_t <symbol>_len`, for zg_context_mount_assets(ctx, "app", <symbol>,
<symbol>_len). The output is reproducible: files are sorted by path.
"""

import argparse
import fnmatch
import struct
import sys
import zlib
from pathlib import Path

MAGIC = b"ZGAR"
VERSION = 1
HEADER = struct.Struct("<4sIII")
ENTRY = struct.Struct("<QQQIIIHBB")
assert HEADER.size == 16 and ENTRY.size == 40

# Already compressed: zlib would only cost time at the first request.
STORED_EXTENSIONS = {
    ".png", ".jpg", ".jpeg", ".gif", ".webp", ".avif", ".ico",
    ".woff", ".woff2",
    ".mp3", ".mp4", ".m4a", ".ogg", ".oga", ".ogv", ".opus", ".webm", ".flac",
    ".zip", ".gz", ".br", ".zst", ".xz", ".7z",
}


def archive_path(root, file):
    relative = file.relative_to(root).as_posix()
    path = "/" + relative
    if any(ord(c) < 0x20 or c in "\\\x7f" for c in path) or any(part in ("", ".", "..") for part in relative.split("/")):
        raise SystemExit(f"error: unsupported file name: {file}")
    return path


def collect(root, excludes):
    files = []
    for file in sorted(root.rglob("*")):
        if not file.is_file():
            continue
        path = archive_path(root, file)
        if any(fnmatch.fnmatch(path.lstrip("/"), pattern) or fnmatch.fnmatch(file.name, pattern) for pattern in excludes):
            continue
        files.append((path, file))
    files.sort(key=lambda item: item[0].encode("utf-8"))
    return files


def pack(files, mime_overrides, compress):
    entries = []
    for path, file in files:
        data = file.read_bytes()
        stored, compression = data, 0
        if compress and file.suffix.lower() not in STORED_EXTENSIONS and data:
            deflated = zlib.compress(data, 9)
            # Worth it only if it saves something real.
            if len(deflated) < len(data) * 0.95:
                stored, compression = deflated, 1
        mime = mime_overrides.get(file.suffix.lower(), "")
        entries.append((path.encode("utf-8"), mime.encode("utf-8"), data, stored, compression))

    table_end = HEADER.size + ENTRY.size * len(entries)
    strings = bytearray()
    string_offsets = []
    for path, mime, *_ in entries:
        path_offset = table_end + len(strings)
        strings += path
        mime_offset = table_end + len(strings)
        strings += mime
        string_offsets.append((path_offset, mime_offset))

    out = bytearray(HEADER.pack(MAGIC, VERSION, len(entries), 0))
    data_offset = table_end + len(strings)
    blobs = bytearray()
    for (path, mime, data, stored, compression), (path_offset, mime_offset) in zip(entries, string_offsets):
        if len(path) > 0xFFFFFFFF or len(mime) > 0xFFFF or len(data) > 0xFFFFFFFF:
            raise SystemExit(f"error: entry too large: {path.decode()}")
        out += ENTRY.pack(data_offset + len(blobs), len(stored), len(data), path_offset, len(path), mime_offset, len(mime), compression, 0)
        blobs += stored
    out += strings
    out += blobs
    return bytes(out), entries


def write_c_source(path, symbol, archive):
    lines = [
        "/* Generated by tools/assets.py: a ZeroG asset archive for zg_context_mount_assets. */",
        "#include <stddef.h>",
        "",
        f"const size_t {symbol}_len = {len(archive)};",
        f"const unsigned char {symbol}[{max(len(archive), 1)}] = {{",
    ]
    for start in range(0, len(archive), 20):
        lines.append("    " + ",".join(str(byte) for byte in archive[start:start + 20]) + ",")
    lines.append("};")
    path.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("directory", type=Path, help="the frontend's build output (e.g. dist/)")
    parser.add_argument("-o", "--output", type=Path, required=True, help="archive (.zga) or, with --c-symbol, C source")
    parser.add_argument("--c-symbol", help="write C source defining this symbol instead of a binary archive")
    parser.add_argument("--mime", action="append", default=[], metavar=".EXT=TYPE", help="MIME type for an extension")
    parser.add_argument("--exclude", action="append", default=[], metavar="PATTERN", help="skip matching files (glob)")
    parser.add_argument("--no-compress", action="store_true", help="store every file uncompressed")
    args = parser.parse_args()

    if not args.directory.is_dir():
        raise SystemExit(f"error: not a directory: {args.directory}")
    if args.c_symbol and not args.c_symbol.isidentifier():
        raise SystemExit(f"error: not a C identifier: {args.c_symbol}")
    overrides = {}
    for item in args.mime:
        extension, _, mime = item.partition("=")
        if not extension.startswith(".") or not mime:
            raise SystemExit(f"error: --mime takes .EXT=TYPE, got {item}")
        overrides[extension.lower()] = mime

    files = collect(args.directory, args.exclude)
    archive, entries = pack(files, overrides, not args.no_compress)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if args.c_symbol:
        write_c_source(args.output, args.c_symbol, archive)
    else:
        args.output.write_bytes(archive)

    size = sum(len(data) for _, _, data, _, _ in entries)
    compressed = sum(1 for *_, compression in entries if compression)
    print(f"{args.output}: {len(entries)} files, {size} bytes in {len(archive)} ({compressed} compressed)")


if __name__ == "__main__":
    sys.exit(main())
