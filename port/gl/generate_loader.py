#!/usr/bin/env python3
"""Generate the EGL/GLES entry points of the Linux GL loader.

The engine links no EGL or GLES library (docs/design/dependencies.md,
"What stays dynamic at runtime"): every EGL and GLES function WebCore and Skia call is defined here and
resolves the driver's implementation on first call (GLLoader.cpp). Prototypes
come from the Khronos headers in the sysroot, which the generated file also
includes, so the compiler checks every signature.

    generate_loader.py OUTPUT INCLUDE_DIR HEADER...
"""

import re
import sys
from pathlib import Path

PROTOTYPE = re.compile(
    r"^(?P<api>EGLAPI|GL_APICALL)\s+(?P<ret>.+?)\s*(?:EGLAPIENTRY|GL_APIENTRY)\s+"
    r"(?P<name>\w+)\s*\((?P<params>.*)\);\s*$")
PARAM_NAME = re.compile(r"(\w+)\s*(?:\[\w*\])?\s*$")


def prototypes(header):
    for line in header.read_text().splitlines():
        match = PROTOTYPE.match(line)
        if match:
            yield match


def argument_names(params):
    params = params.strip()
    if params in ("", "void"):
        return []
    names = []
    for param in params.split(","):
        match = PARAM_NAME.search(param)
        if not match:
            sys.exit(f"cannot parse parameter {param!r}")
        names.append(match.group(1))
    return names


def stub(match):
    ret, name, params = match["ret"].strip(), match["name"], match["params"].strip()
    library = "EGL" if match["api"] == "EGLAPI" else "GLES"
    entry = "EGLAPIENTRY" if library == "EGL" else "GL_APIENTRY"
    call = f"function({', '.join(argument_names(params))})"
    if ret == "void":
        body = f"    if (function)\n        {call};"
    else:
        body = f"    if (!function)\n        return {{ }};\n    return {call};"
    return (f"extern \"C\" {ret} {entry} {name}({params})\n"
            "{\n"
            f"    static auto* function = reinterpret_cast<decltype(&{name})>(ZeroG::GL::resolve(ZeroG::GL::Library::{library}, \"{name}\"));\n"
            f"{body}\n"
            "}\n")


def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    output, include_dir, headers = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3:]
    seen = set()
    stubs = []
    for header in headers:
        for match in prototypes(include_dir / header):
            if match["name"] not in seen:
                seen.add(match["name"])
                stubs.append(stub(match))

    lines = ["// Generated by port/gl/generate_loader.py from the Khronos headers. Do not edit.", ""]
    lines.append('#include "GLLoader.h"')
    lines.append("")
    lines += [f"#include <{header}>" for header in headers]
    lines.append("")
    text = "\n".join(lines) + "\n" + "\n".join(stubs)
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text() != text:
        output.write_text(text)
    print(f"{output.name}: {len(stubs)} entry points")


if __name__ == "__main__":
    main()
